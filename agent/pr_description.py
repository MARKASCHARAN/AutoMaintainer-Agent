import subprocess


def generate_pr_description(repo_path: str, plan: dict, verify_result) -> str:
    """
    Builds a human-style PR description using diff + plan + verification.
    """

    def run_git(cmd):
        try:
            return subprocess.run(
                cmd,
                cwd=repo_path,
                capture_output=True,
                text=True
            ).stdout.strip()
        except Exception:
            return ""

    # -----------------------------
    # Get changed files (robust)
    # -----------------------------
    diff_files = run_git(["git", "diff", "--name-only", "HEAD~1"])
    if not diff_files:
        diff_files = run_git(["git", "diff", "--name-only", "--cached"])

    files_list = diff_files.splitlines() if diff_files else ["(no files detected)"]

    # -----------------------------
    # Diff stats
    # -----------------------------
    diff_stats = run_git(["git", "diff", "--stat", "HEAD~1"])
    if not diff_stats:
        diff_stats = run_git(["git", "diff", "--stat", "--cached"])
    if not diff_stats:
        diff_stats = "(no diff stats available)"

    # -----------------------------
    # Plan summary
    # -----------------------------
    summary = plan.get("summary", "Automated fix generated by AutoMaintainer")

    # -----------------------------
    # Confidence
    # -----------------------------
    confidence = "High" if verify_result and verify_result.success else "Medium"

    # -----------------------------
    # Validation output
    # -----------------------------
    validation_snippet = (
        verify_result.output[:800].strip()
        if verify_result and getattr(verify_result, "output", None)
        else "No verification output available."
    )

    # -----------------------------
    # Final PR body
    # -----------------------------
    body = f"""## 🤖 AutoMaintainer Fix

### Summary
{summary}

### Impact
Restores successful installation, validation, and project stability based on automated verification.

### Files changed
{chr(10).join(f"- `{f}`" for f in files_list)}

### Why this change
The agent analyzed the repository, identified the most likely root cause of the failure, and applied targeted fixes to resolve underlying issues rather than applying superficial workarounds.

### Validation performed
```text
{validation_snippet}

### Diff overview

{diff_stats}

### Confidence level
{confidence} — validated through real dependency installation and successful automated verification.
"""
    return body.strip()