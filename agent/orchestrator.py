from agent.observer import observe_repo
from agent.diagnoser import diagnose_issue
from agent.planner import plan_fix
from agent.executor import execute_plan, git_commit
from agent.verifier import verify_fix

from agent.github_client import (
    create_branch,
    push_changes,
    create_pull_request
)

MAX_ATTEMPTS = 3


def run_agent(repo_url: str):
    print("\n=== AutoMaintainer Agent Started ===")

    context = observe_repo(repo_url)
    repo_path = context["local_path"]

    diagnosis = diagnose_issue(context)

    last_feedback = None

    for attempt in range(1, MAX_ATTEMPTS + 1):
        print(f"\n--- Attempt {attempt}/{MAX_ATTEMPTS} ---")

        # 1. Plan
        plan = plan_fix(diagnosis, last_feedback)

        if not isinstance(plan, dict):
            last_feedback = f"Planner returned non-dict: {plan}"
            print("❌ Invalid plan format")
            continue

        if "patches" not in plan:
            last_feedback = f"Planner missing patches field: {plan}"
            print("❌ Plan missing patches")
            continue

        # 2. Execute
        applied = execute_plan(plan, repo_path)

        # 3. Verify
        result = verify_fix(plan, repo_path)

        # 4. SUCCESS PATH
        if result.success:
            print("✅ Tests passed")

            if applied:
                # Commit locally
                git_commit(
                    repo_path,
                    f"AutoMaintainer: applied automated fix in {attempt} attempt(s)"
                )

                # Create branch
                branch = create_branch(repo_path)

                # Push changes
                push_changes(repo_path)

                # Open PR
                pr_url = create_pull_request(
                    repo_url=repo_url,
                    branch=branch,
                    title=f"AutoMaintainer Fix ({attempt} attempt)",
                    body=plan.get(
                        "summary",
                        "Automated fix generated by AutoMaintainer agent."
                    )
                )

                return {
                    "status": "success",
                    "attempts": attempt,
                    "applied": applied,
                    "pr": pr_url,
                    "output": result.output[-2000:]
                }

            else:
                print("[Orchestrator] No changes applied, skipping PR")

                return {
                    "status": "success",
                    "attempts": attempt,
                    "applied": [],
                    "output": result.output[-2000:]
                }

        # 5. FAILURE PATH
        print("❌ Tests failed, retrying...")
        last_feedback = result.output[-4000:]

    # All attempts exhausted
    return {
        "status": "failed",
        "attempts": MAX_ATTEMPTS,
        "last_output": last_feedback
    }
